import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

import { icu } from '@parlajs/format-icu';
import { mf2 } from '@parlajs/format-mf2';
import type { Model } from 'messageformat';

import { CompileError, compileMessage, ModuleScope } from './compile.ts';
import type { MessageInfo } from './compile.ts';
import { fallbackChain, loadConfig } from './config.ts';
import type { ResolvedConfig, ResolvedNamespace } from './config.ts';
import { interfaceName, namespaceInterface, paramType } from './types.ts';

export interface FormatAdapter {
  readonly name: string;
  readonly parse: (source: string) => Model.Message;
}

export const defaultFormats: Record<string, FormatAdapter> = { icu, mf2 };

export interface Diagnostic {
  level: 'error' | 'warning';
  code:
    | 'invalid-syntax'
    | 'invalid-resource'
    | 'missing-file'
    | 'missing-translation'
    | 'unknown-key'
    | 'param-mismatch'
    | 'key-conflict'
    | 'unknown-format';
  message: string;
  namespace?: string;
  locale?: string;
  key?: string;
  file?: string;
}

export interface BuildOptions {
  cwd?: string;
  /** Path to the config file, relative to `cwd`. */
  config?: string | undefined;
  formats?: Record<string, FormatAdapter> | undefined;
  /** `all` writes chunks and types, `types` only `catalog.d.ts`, `false` writes nothing (check). */
  write?: 'all' | 'types' | false | undefined;
}

export interface BuildResult {
  config: ResolvedConfig;
  diagnostics: Array<Diagnostic>;
  written: Array<string>;
}

const HEADER = '// Generated by parla. Do not edit.\n';

// oxlint-disable-next-line typescript/no-empty-object-type -- a type alias cannot refer to itself here
interface ChunkTree extends Map<string, ChunkTree | string> {}

/** Dotted keys as nested groups; `key-conflict` already rules out a key that is also a group. */
function treeOf(messages: ReadonlyArray<[key: string, fn: string]>): ChunkTree {
  const root: ChunkTree = new Map();
  for (const [key, fn] of messages) {
    const path = key.split('.');
    const leaf = path.pop() ?? key;
    let node = root;
    for (const segment of path) {
      let child = node.get(segment);
      if (typeof child !== 'object') {
        child = new Map();
        node.set(segment, child);
      }
      node = child;
    }
    node.set(leaf, fn);
  }
  return root;
}

// A literal `"__proto__": …` would set the prototype; a computed key defines a property.
const literalKey = (key: string): string =>
  key === '__proto__' ? '["__proto__"]' : JSON.stringify(key);

// V8 builds a literal of up to 127 properties from a template; at 128 it takes a path ~100× slower.
const MAX_LITERAL = 127;

/** A group as an expression that builds it: one literal, or one plus assignments when larger. */
function emitGroup(node: ChunkTree, indent: string): string {
  const inner = `${indent}  `;
  const value = (v: ChunkTree | string): string =>
    typeof v === 'string' ? v : emitGroup(v, inner);
  // `__proto__` must stay in the literal: an assignment would set the prototype.
  const entries = [...node].toSorted(
    ([a], [b]) => Number(b === '__proto__') - Number(a === '__proto__'),
  );
  const literal = entries
    .slice(0, MAX_LITERAL)
    .map(([key, v]) => `${inner}${literalKey(key)}: ${value(v)},`)
    .join('\n');
  if (entries.length <= MAX_LITERAL) {
    return `{\n${literal}\n${indent}}`;
  }
  const rest = entries
    .slice(MAX_LITERAL)
    .map(([key, v]) => `${inner}o[${JSON.stringify(key)}] = ${value(v)};`)
    .join('\n');
  return `(() => {\n${inner}const o = {\n${literal}\n${inner}};\n${rest}\n${inner}return o;\n${indent}})()`;
}

function flatten(
  value: unknown,
  prefix: string,
  out: Map<string, string>,
  report: (key: string, msg: string) => void,
): void {
  if (typeof value === 'string') {
    out.set(prefix, value);
    return;
  }
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [k, v] of Object.entries(value)) {
      flatten(v, prefix ? `${prefix}.${k}` : k, out, report);
    }
    return;
  }
  report(
    prefix,
    `expected a string or an object, got ${Array.isArray(value) ? 'array' : typeof value}`,
  );
}

interface Entry {
  source: string;
  model: Model.Message;
}

function readCatalog(
  ns: ResolvedNamespace,
  locale: string,
  adapter: FormatAdapter,
  diag: (d: Omit<Diagnostic, 'namespace' | 'locale'>) => void,
): { file: string; entries: Map<string, Entry>; exists: boolean } {
  const file = ns.file(locale);
  const entries = new Map<string, Entry>();
  if (!existsSync(file)) {
    return { file, entries, exists: false };
  }
  let json: unknown;
  try {
    json = JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    diag({ level: 'error', code: 'invalid-resource', message: (error as Error).message, file });
    return { file, entries, exists: true };
  }
  const flat = new Map<string, string>();
  flatten(json, '', flat, (key, message) => {
    diag({ level: 'error', code: 'invalid-resource', key, message, file });
  });
  const keys = [...flat.keys()].toSorted();
  for (const [i, key] of keys.entries()) {
    if (keys[i + 1]?.startsWith(`${key}.`)) {
      diag({
        level: 'error',
        code: 'key-conflict',
        key,
        message: `"${key}" is both a message and a group`,
        file,
      });
    }
  }
  for (const [key, source] of flat) {
    try {
      entries.set(key, { source, model: adapter.parse(source) });
    } catch (error) {
      diag({
        level: 'error',
        code: 'invalid-syntax',
        key,
        message: (error as Error).message,
        file,
      });
    }
  }
  return { file, entries, exists: true };
}

function writeIfChanged(file: string, content: string, written: Array<string>): void {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) {
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  written.push(file);
}

export function build(options: BuildOptions = {}): BuildResult {
  const cwd = options.cwd ?? process.cwd();
  const formats = { ...defaultFormats, ...options.formats };
  const write = options.write ?? 'all';
  const config = loadConfig(cwd, options.config);
  const diagnostics: Array<Diagnostic> = [];
  const written: Array<string> = [];
  const chunks = new Map<string, string>();
  const interfaces: Array<string> = [];

  for (const ns of config.namespaces) {
    const adapter = formats[ns.format];
    if (!adapter) {
      diagnostics.push({
        level: 'error',
        code: 'unknown-format',
        namespace: ns.name,
        message: `unknown format "${ns.format}". Known: ${Object.keys(formats).join(', ')}`,
      });
      continue;
    }
    const catalogs = new Map<string, Map<string, Entry>>();
    const missingFile = new Set<string>();
    for (const locale of config.locales) {
      const read = readCatalog(ns, locale, adapter, (d) => {
        diagnostics.push({ ...d, namespace: ns.name, locale });
      });
      if (!read.exists) {
        missingFile.add(locale);
        diagnostics.push({
          level: locale === config.sourceLocale ? 'error' : 'warning',
          code: 'missing-file',
          namespace: ns.name,
          locale,
          file: read.file,
          message:
            ns.owner === '.'
              ? `${relative(config.root, read.file)} does not exist`
              : `${relative(config.root, read.file)} does not exist; does "${ns.owner}" publish it (package.json "files")?`,
        });
      }
      catalogs.set(locale, read.entries);
    }

    const source = catalogs.get(config.sourceLocale) ?? new Map<string, Entry>();
    const sourceInfo = new Map<string, { info: MessageInfo; source: string }>();

    for (const locale of config.locales) {
      const scope = new ModuleScope();
      const messages: Array<[key: string, fn: string]> = [];
      const hoisted: Array<string> = [];
      const own = catalogs.get(locale) ?? new Map<string, Entry>();
      const chain = fallbackChain(config, locale);
      const at = (d: Omit<Diagnostic, 'namespace' | 'locale'>): void => {
        diagnostics.push({ ...d, namespace: ns.name, locale, file: ns.file(locale) });
      };

      for (const key of [...own.keys()].filter((k) => !source.has(k))) {
        at({
          level: 'warning',
          code: 'unknown-key',
          key,
          message: `not in the source locale "${config.sourceLocale}"; dropped`,
        });
      }

      for (const [key, srcEntry] of source) {
        let entry = own.get(key);
        if (!entry) {
          const from = chain.find((l) => catalogs.get(l)?.has(key));
          entry = from ? catalogs.get(from)?.get(key) : undefined;
          if (!missingFile.has(locale)) {
            at({
              level: 'warning',
              code: 'missing-translation',
              key,
              message: from ? `using "${from}"` : 'no fallback',
            });
          }
          if (!entry) {
            continue;
          }
        }
        let compiled;
        try {
          compiled = compileMessage(entry.model, scope);
        } catch (error) {
          if (!(error instanceof CompileError)) {
            throw error;
          }
          at({ level: 'error', code: 'invalid-syntax', key, message: error.message });
          continue;
        }
        if (locale === config.sourceLocale) {
          sourceInfo.set(key, { info: compiled.info, source: srcEntry.source });
        } else if (own.has(key)) {
          let ref = sourceInfo.get(key);
          if (!ref) {
            try {
              ref = { info: compileMessage(srcEntry.model).info, source: srcEntry.source };
            } catch {
              // The source message's own error is reported for the source locale.
            }
          }
          if (ref) {
            for (const [param, kinds] of compiled.info.params) {
              const expected = ref.info.params.get(param);
              if (!expected) {
                at({
                  level: 'error',
                  code: 'param-mismatch',
                  key,
                  message: `uses $${param}, which the source message does not have`,
                });
              } else if (
                paramType(kinds) !== paramType(expected) &&
                paramType(kinds) !== 'string | number'
              ) {
                at({
                  level: 'error',
                  code: 'param-mismatch',
                  key,
                  message: `$${param} is ${paramType(kinds)} here but ${paramType(expected)} in the source`,
                });
              }
            }
            for (const tag of compiled.info.markup) {
              if (!ref.info.markup.has(tag)) {
                at({
                  level: 'error',
                  code: 'param-mismatch',
                  key,
                  message: `uses markup "${tag}", which the source message does not have`,
                });
              }
            }
          }
        }
        // A message that never reads `p` takes no default, so a call without params allocates nothing.
        const param = /\bp\b/.test(compiled.body) ? 'p = {}' : 'p';
        const fn = `(${param}) => ${compiled.body}`;
        // One that never reads `$` is created once per module, not on every load.
        if (compiled.body.includes('$.')) {
          messages.push([key, fn]);
        } else {
          const name = `m${hoisted.length}`;
          hoisted.push(`const ${name} = ${fn};`);
          messages.push([key, name]);
        }
      }

      const declared = [...scope.consts, ...hoisted];
      const consts = declared.length > 0 ? `${declared.join('\n')}\n` : '';
      chunks.set(
        join('messages', locale, `${ns.name}.js`),
        `${HEADER}${consts}export default ($) => (${emitGroup(treeOf(messages), '')});\n`,
      );
    }
    interfaces.push(namespaceInterface(ns.name, sourceInfo));
  }

  if (write) {
    const out = config.outDir;
    const localeType = config.locales.map((l) => JSON.stringify(l)).join(' | ');
    const nsEntries = config.namespaces
      .map((ns) => `      ${JSON.stringify(ns.name)}: ${interfaceName(ns.name)};`)
      .join('\n');
    writeIfChanged(
      join(out, 'catalog.d.ts'),
      `${HEADER}import type { Catalog, RichNode } from '${config.runtime}';\n\n${interfaces.join('\n\n')}\n\nexport type Locale = ${localeType};\n\nexport declare const catalog: Catalog & { readonly locales: readonly Locale[]; readonly sourceLocale: ${JSON.stringify(config.sourceLocale)} };\n\ndeclare module '${config.runtime}' {\n  interface Register {\n    locale: ${localeType};\n    namespaces: {\n${nsEntries}\n    };\n  }\n}\n`,
      written,
    );
    if (write === 'all') {
      const loaders = config.namespaces
        .map((ns) => {
          const perLocale = config.locales
            .map(
              (l) =>
                `      ${JSON.stringify(l)}: () => import(${JSON.stringify(`./messages/${l}/${ns.name}.js`)}),`,
            )
            .join('\n');
          return `    ${JSON.stringify(ns.name)}: {\n${perLocale}\n    },`;
        })
        .join('\n');
      writeIfChanged(
        join(out, 'catalog.js'),
        `${HEADER}export const catalog = {\n  locales: ${JSON.stringify(config.locales)},\n  sourceLocale: ${JSON.stringify(config.sourceLocale)},\n  namespaces: {\n${loaders}\n  },\n};\n`,
        written,
      );
      for (const [rel, code] of chunks) {
        writeIfChanged(join(out, rel), code, written);
      }
      const messagesDir = join(out, 'messages');
      for (const locale of existsSync(messagesDir) ? readdirSync(messagesDir) : []) {
        for (const file of readdirSync(join(messagesDir, locale))) {
          if (!chunks.has(join('messages', locale, file))) {
            rmSync(join(messagesDir, locale, file));
          }
        }
      }
    }
  }

  return { config, diagnostics, written };
}

export function formatDiagnostic(d: Diagnostic, root?: string): string {
  const where = [d.namespace, d.locale, d.key].filter(Boolean).join(' › ');
  const file = d.file && root ? ` (${relative(root, d.file)})` : '';
  return `${d.level === 'error' ? 'error  ' : 'warning'} [${d.code}] ${where}: ${d.message}${file}`;
}
