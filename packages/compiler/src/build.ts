export interface FormatAdapter {
  readonly name: string;
  readonly parse: (source: string) => Model.Message;
}

export const defaultFormats: Record<string, FormatAdapter> = { icu, mf2 };

export interface Diagnostic {
  level: 'error' | 'warning';
  code:
    | 'invalid-syntax'
    | 'invalid-resource'
    | 'missing-file'
    | 'missing-translation'
    | 'unknown-key'
    | 'param-mismatch'
    | 'key-conflict'
    | 'unknown-format';
  message: string;
  namespace?: string;
  locale?: string;
  key?: string;
  file?: string;
}

export interface BuildOptions {
  cwd?: string;
  /** Path to the config file, relative to `cwd`. */
  config?: string | undefined;
  formats?: Record<string, FormatAdapter> | undefined;
  /** `false` writes nothing: a check. */
  write?: boolean | undefined;
}

export interface BuildResult {
  config: ResolvedConfig;
  diagnostics: Array<Diagnostic>;
  written: Array<string>;
}

const HEADER = '// Generated by parla. Do not edit.\n';

// oxlint-disable-next-line typescript/no-empty-object-type -- a type alias cannot refer to itself here
interface ChunkTree extends Map<string, ChunkTree | string> {}

/** Dotted keys as nested groups; `key-conflict` already rules out a key that is also a group. */
function treeOf(messages: ReadonlyArray<[key: string, fn: string]>): ChunkTree {
  const root: ChunkTree = new Map();
  for (const [key, fn] of messages) {
    const path = key.split('.');
    const leaf = path.pop() ?? key;
    let node = root;
    for (const segment of path) {
      let child = node.get(segment);
      if (typeof child !== 'object') {
        child = new Map();
        node.set(segment, child);
      }
      node = child;
    }
    node.set(leaf, fn);
  }
  return root;
}

// A literal `"__proto__": …` would set the prototype; a computed key defines a property.
const literalKey = (key: string): string =>
  key === '__proto__' ? '["__proto__"]' : JSON.stringify(key);

// V8 builds a literal of up to 127 properties from a template; at 128 it takes a path ~100× slower.
const MAX_LITERAL = 127;

/** A group as an expression that builds it: one literal, or one plus assignments when larger. */
function emitGroup(node: ChunkTree, indent: string): string {
  const inner = `${indent}  `;
  const value = (v: ChunkTree | string): string =>
    typeof v === 'string' ? v : emitGroup(v, inner);
  // `__proto__` must stay in the literal: an assignment would set the prototype.
  const entries = [...node].toSorted(
    ([a], [b]) => Number(b === '__proto__') - Number(a === '__proto__'),
  );
  const literal = entries
    .slice(0, MAX_LITERAL)
    .map(([key, v]) => `${inner}${literalKey(key)}: ${value(v)},`)
    .join('\n');
  if (entries.length <= MAX_LITERAL) {
    return `{\n${literal}\n${indent}}`;
  }
  const rest = entries
    .slice(MAX_LITERAL)
    .map(([key, v]) => `${inner}o[${JSON.stringify(key)}] = ${value(v)};`)
    .join('\n');
  return `(() => {\n${inner}const o = {\n${literal}\n${inner}};\n${rest}\n${inner}return o;\n${indent}})()`;
}

function flatten(
  value: unknown,
  prefix: string,
  out: Map<string, string>,
  report: (key: string, msg: string) => void,
): void {
  if (typeof value === 'string') {
    out.set(prefix, value);
    return;
  }
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [k, v] of Object.entries(value)) {
      flatten(v, prefix ? `${prefix}.${k}` : k, out, report);
    }
    return;
  }
  report(
    prefix,
    `expected a string or an object, got ${Array.isArray(value) ? 'array' : typeof value}`,
  );
}

interface Entry {
  source: string;
  model: Model.Message;
}

function readCatalog(
  ns: ResolvedNamespace,
  locale: string,
  adapter: FormatAdapter,
  diag: (d: Omit<Diagnostic, 'namespace' | 'locale'>) => void,
): { file: string; entries: Map<string, Entry>; exists: boolean } {
  const file = ns.file(locale);
  const entries = new Map<string, Entry>();
  if (!existsSync(file)) {
    return { file, entries, exists: false };
  }
  let json: unknown;
  try {
    json = JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    diag({ level: 'error', code: 'invalid-resource', message: (error as Error).message, file });
    return { file, entries, exists: true };
  }
  const flat = new Map<string, string>();
  flatten(json, '', flat, (key, message) => {
    diag({ level: 'error', code: 'invalid-resource', key, message, file });
  });
  const keys = [...flat.keys()].toSorted();
  for (const [i, key] of keys.entries()) {
    if (keys[i + 1]?.startsWith(`${key}.`)) {
      diag({
        level: 'error',
        code: 'key-conflict',
        key,
        message: `"${key}" is both a message and a group`,
        file,
      });
    }
  }
  for (const [key, source] of flat) {
    try {
      entries.set(key, { source, model: adapter.parse(source) });
    } catch (error) {
      diag({
        level: 'error',
        code: 'invalid-syntax',
        key,
        message: (error as Error).message,
        file,
      });
    }
  }
  return { file, entries, exists: true };
}

/** One registry augmentation, or nothing when it has no member. */
function registry(name: string, keys: ReadonlyArray<string>): string {
  const members = keys.map((k) => `    ${JSON.stringify(k)}: true;\n`).join('');
  return members ? `  interface ${name} {\n${members}  }\n` : '';
}

/** A translation's params and markup against the source message's. */
function mismatches(own: MessageInfo, source: MessageInfo): Array<string> {
  const out: Array<string> = [];
  for (const [param, kinds] of own.params) {
    const expected = source.params.get(param);
    if (!expected) {
      out.push(`uses $${param}, which the source message does not have`);
    } else if (paramType(kinds) !== paramType(expected) && paramType(kinds) !== 'string | number') {
      out.push(`$${param} is ${paramType(kinds)} here but ${paramType(expected)} in the source`);
    }
  }
  for (const tag of own.markup) {
    if (!source.markup.has(tag)) {
      out.push(`uses markup "${tag}", which the source message does not have`);
    }
  }
  const { branches } = source;
  if (branches) {
    // The source's type lets a call leave out what its value's branch does not read.
    const ownBranches = own.branches?.param === branches.param ? own.branches : undefined;
    const needs = (info: MessageInfo, key: string | null): Set<string> => {
      const map = info === source ? branches : ownBranches;
      return map?.needs.get(key) ?? map?.needs.get(null) ?? new Set(info.params.keys());
    };
    const keys = new Set([...branches.needs.keys(), ...(ownBranches?.needs.keys() ?? [])]);
    const reported = new Set<string>();
    for (const key of keys) {
      const allowed = needs(source, key);
      for (const param of needs(own, key)) {
        if (source.params.has(param) && !allowed.has(param) && !reported.has(param)) {
          reported.add(param);
          const when = key === null ? 'another value' : JSON.stringify(key);
          out.push(`needs $${param} when $${branches.param} is ${when}, but the source does not`);
        }
      }
    }
  }
  return out;
}

/**
 * Writes through a dotted temp file and a rename: builds run at once (one per app of a monorepo, the
 * dev server beside `tsc --watch`) must never read a half-written chunk.
 */
function writeIfChanged(file: string, content: string, written: Array<string>): void {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) {
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  const tmp = join(dirname(file), `.${basename(file)}.${process.pid}.tmp`);
  writeFileSync(tmp, content);
  renameSync(tmp, file);
  written.push(file);
}

/** Removes the files in `dir` that this build did not generate. */
function removeStale(dir: string, rel: string, kept: ReadonlyMap<string, string>): void {
  for (const file of existsSync(dir) ? readdirSync(dir) : []) {
    // a dotted file is another build's write in progress; a parallel build may remove first
    if (!file.startsWith('.') && !kept.has(join(rel, file))) {
      rmSync(join(dir, file), { force: true });
    }
  }
}

const localeType = (config: ResolvedConfig): string =>
  config.locales.map((l) => JSON.stringify(l)).join(' | ');

/**
 * The namespace object's type: its messages, a kind that hands them the instance's node type when
 * they have markup, and the locales it was built for.
 */
function namespaceDeclaration(
  namespace: string,
  iface: string,
  config: ResolvedConfig,
  messages: Map<string, { info: MessageInfo; source: string }>,
): string {
  const types = namespaceTypes(messages, iface, new Set(config.markup));
  const kind = iface.replace(/Messages$/, 'Kind');
  const imported = ['Namespace', 'NamespaceKind', ...(types.usesText ? ['Text'] : [])];
  return `${HEADER}import type { ${imported.join(', ')} } from '${config.runtime}';

${types.code}

export interface ${kind} extends NamespaceKind {
  readonly messages: ${iface}${types.generic ? "<this['node']>" : ''};
}

export declare const ${exportName(namespace, iface)}: Namespace<${JSON.stringify(namespace)}, ${kind}, ${localeType(config)}>;
`;
}

/** What an app imports to load a namespace: its name and one chunk loader per locale. */
function namespaceModule(namespace: string, iface: string, locales: ReadonlyArray<string>): string {
  const loaders = locales
    .map(
      (l) =>
        `    ${JSON.stringify(l)}: () => import(${JSON.stringify(`../messages/${l}/${namespace}.js`)}),`,
    )
    .join('\n');
  return `${HEADER}export const ${exportName(namespace, iface)} = {\n  name: ${JSON.stringify(namespace)},\n  load: {\n${loaders}\n  },\n};\n`;
}

export async function build(options: BuildOptions = {}): Promise<BuildResult> {
  const cwd = options.cwd ?? process.cwd();
  const formats = { ...defaultFormats, ...options.formats };
  const write = options.write ?? true;
  const config = await loadConfig(cwd, options.config);
  const diagnostics: Array<Diagnostic> = [];
  const written: Array<string> = [];
  const files = new Map<string, string>();
  const names = interfaceNames(config.namespaces.map((ns) => ns.name));
  const nameOf = (namespace: string): string => names.get(namespace) ?? '';
  // The source locale first, so every translation has its source message to compare against.
  const locales = [config.sourceLocale, ...config.locales.filter((l) => l !== config.sourceLocale)];

  for (const ns of config.namespaces) {
    const adapter = formats[ns.format];
    if (!adapter) {
      diagnostics.push({
        level: 'error',
        code: 'unknown-format',
        namespace: ns.name,
        message: `unknown format "${ns.format}". Known: ${Object.keys(formats).join(', ')}`,
      });
      continue;
    }
    const catalogs = new Map<string, Map<string, Entry>>();
    const missingFile = new Set<string>();
    for (const locale of config.locales) {
      const read = readCatalog(ns, locale, adapter, (d) => {
        diagnostics.push({ ...d, namespace: ns.name, locale });
      });
      if (!read.exists) {
        missingFile.add(locale);
        diagnostics.push({
          level: locale === config.sourceLocale ? 'error' : 'warning',
          code: 'missing-file',
          namespace: ns.name,
          locale,
          file: read.file,
          message: `${relative(config.root, read.file)} does not exist`,
        });
      }
      catalogs.set(locale, read.entries);
    }

    const source = catalogs.get(config.sourceLocale) ?? new Map<string, Entry>();
    const sourceInfo = new Map<string, { info: MessageInfo; source: string }>();

    for (const locale of locales) {
      const scope = new ModuleScope();
      const messages: Array<[key: string, fn: string]> = [];
      const own = catalogs.get(locale) ?? new Map<string, Entry>();
      const chain = fallbackChain(config, locale);
      const at = (d: Omit<Diagnostic, 'namespace' | 'locale'>): void => {
        diagnostics.push({ ...d, namespace: ns.name, locale, file: ns.file(locale) });
      };

      for (const key of [...own.keys()].filter((k) => !source.has(k))) {
        at({
          level: 'warning',
          code: 'unknown-key',
          key,
          message: `not in the source locale "${config.sourceLocale}"; dropped`,
        });
      }

      for (const [key, srcEntry] of source) {
        let entry = own.get(key);
        if (!entry) {
          const from = chain.find((l) => catalogs.get(l)?.has(key));
          entry = from ? catalogs.get(from)?.get(key) : undefined;
          if (!missingFile.has(locale)) {
            at({
              level: 'warning',
              code: 'missing-translation',
              key,
              message: from ? `using "${from}"` : 'no fallback',
            });
          }
          if (!entry) {
            continue;
          }
        }
        let compiled;
        try {
          compiled = compileMessage(entry.model, scope, config.functions);
        } catch (error) {
          if (!(error instanceof CompileError)) {
            throw error;
          }
          at({ level: 'error', code: 'invalid-syntax', key, message: error.message });
          continue;
        }
        if (locale === config.sourceLocale) {
          sourceInfo.set(key, { info: compiled.info, source: srcEntry.source });
        } else if (own.has(key)) {
          // A source message that fails to compile is reported for the source locale.
          const ref = sourceInfo.get(key);
          for (const message of ref ? mismatches(compiled.info, ref.info) : []) {
            at({ level: 'error', code: 'param-mismatch', key, message });
          }
        }
        // A message that never reads `p` takes no default, so a call without params allocates nothing.
        const param = /\bp\b/.test(compiled.body) ? 'p = {}' : 'p';
        messages.push([key, `(${param}) => ${compiled.body}`]);
      }

      const consts = scope.consts.length > 0 ? `${scope.consts.join('\n')}\n` : '';
      files.set(
        join('messages', locale, `${ns.name}.js`),
        `${HEADER}${consts}export default ($) => (${emitGroup(treeOf(messages), '')});\n`,
      );
    }
    files.set(
      join('namespaces', `${ns.name}.js`),
      namespaceModule(ns.name, nameOf(ns.name), config.locales),
    );
    files.set(
      join('namespaces', `${ns.name}.d.ts`),
      namespaceDeclaration(ns.name, nameOf(ns.name), config, sourceInfo),
    );
  }

  if (write) {
    const out = config.outDir;
    const registries = [
      registry('LocaleRegistry', config.locales),
      registry('FunctionRegistry', Object.keys(config.functions)),
      registry('MarkupRegistry', config.markup),
    ].join('');
    files.set(
      'catalog.js',
      `${HEADER}export const catalog = {\n  locales: ${JSON.stringify(config.locales)},\n  sourceLocale: ${JSON.stringify(config.sourceLocale)},\n};\n`,
    );
    files.set(
      'catalog.d.ts',
      `${HEADER}import type { Catalog } from '${config.runtime}';\n\nexport type Locale = ${localeType(config)};\n\nexport declare const catalog: Catalog & { readonly locales: readonly Locale[]; readonly sourceLocale: ${JSON.stringify(config.sourceLocale)} };\n\ndeclare module '${config.runtime}' {\n${registries}}\n`,
    );
    for (const [rel, code] of files) {
      writeIfChanged(join(out, rel), code, written);
    }
    removeStale(join(out, 'namespaces'), 'namespaces', files);
    const messagesDir = join(out, 'messages');
    for (const locale of existsSync(messagesDir) ? readdirSync(messagesDir) : []) {
      removeStale(join(messagesDir, locale), join('messages', locale), files);
    }
  }

  return { config, diagnostics, written };
}

export function formatDiagnostic(d: Diagnostic, root?: string): string {
  const where = [d.namespace, d.locale, d.key].filter(Boolean).join(' › ');
  const file = d.file && root ? ` (${relative(root, d.file)})` : '';
  return `${d.level === 'error' ? 'error  ' : 'warning'} [${d.code}] ${where}: ${d.message}${file}`;
}
